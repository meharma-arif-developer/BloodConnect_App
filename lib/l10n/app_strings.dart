import 'language_controller.dart';
import 'machine_translator.dart';

/// Urdu translations for the app's fixed texts (English is the default).
/// Texts that contain names or numbers (for example "Ali needs O+ blood")
/// and the long legal paragraphs are not translated yet and stay in English.
class AppStrings {
  AppStrings._();

  /// Translate using an explicit language code ('en' or 'ur').
  static String translate(String text, String code) {
    if (code == 'en') return text;
    if (code == 'ur') return _ur[text] ?? _ur[text.trim()] ?? text;

    // Other languages: only the app's own fixed texts are machine-translated
    // (never names, chat messages or other user data).
    if (_ur.containsKey(text)) {
      return MachineTranslator.instance.lookup(text, code);
    }
    return text;
  }

  /// Translate using the app's current language (for texts without a context).
  static String tr(String text) =>
      translate(text, LanguageController.instance.code);
}

